# Генератор тестовых файлов с лидами: Excel (2 листа), CSV (cp1251, «;»), Word (таблица + текст).
# Данные вымышленные.
from datetime import datetime
from pathlib import Path

import docx
from openpyxl import Workbook

OUT = Path(__file__).parent / "fixtures"

# Excel: лист 1 — заголовок в первой строке; лист 2 — шапка отчёта сверху, заголовок в 4-й строке,
# телефоны числами, дата — настоящая дата Excel, лишние колонки
wb = Workbook()
ws = wb.active
ws.title = "Лиды"
ws.append(["Дата лида", "lead_phone", "запрошенная сумма", "инн лида", "компания лида"])
ws.append(["05.07.2026 23:53:51", "79001110001", "1 000 000", "410100000001", "ИП Смирнова Ольга Петровна"])
ws.append(["05.07.2026 21:50:30", "79001110002", "1 500 000", "710000000002", "ООО \"ЛУЧ\""])
ws2 = wb.create_sheet("Октябрь")
ws2.append(["Выгрузка заявок"])
ws2.append(["за октябрь 2026"])
ws2.append([])
ws2.append(["№", "Дата создания", "ФИО клиента", "Номер телефона", "Сумма кредита", "Комментарий"])
ws2.append([1, datetime(2026, 10, 1, 12, 30), "Орлов Иван Сергеевич", 79001110003, 300000, "срочно"])
ws2.append([2, datetime(2026, 10, 2), "Белова Анна", 89001110004, 750000.0, None])
ws2.append([3, datetime(2026, 10, 3), "Без телефона", None, 100000, None])
wb.save(OUT / "leads.xlsx")

# CSV, как сохраняет русский Excel: cp1251 и «;»
csv_text = ("Телефон;Клиент;Форма;Сумма;Дата\n"
            "+7 (900) 111-00-05;Кузнецов Павел Андреевич;ИП;2 000 000;12.10.2026\n"
            "8 900 111 00 06;Альфа;ООО;500000;13.10.2026\n")
(OUT / "leads.csv").write_bytes(csv_text.encode("cp1251"))

# Word: таблица с заголовком + обычный абзац с ещё одним клиентом
d = docx.Document()
d.add_paragraph("Список заявок за неделю")
t = d.add_table(rows=1, cols=3)
for c, h in zip(t.rows[0].cells, ["ФИО", "Телефон", "Сумма"]):
    c.text = h
for row in [("Лебедев Игорь Олегович", "+79001110007", "400 000"), ("Новикова Мария", "+79001110008", "1 200 000")]:
    for c, v in zip(t.add_row().cells, row):
        c.text = v
d.add_paragraph("Также звонила ООО Вектор, тел. 8 (900) 111-00-09, нужна сумма 900 000 руб.")
d.save(OUT / "leads.docx")
